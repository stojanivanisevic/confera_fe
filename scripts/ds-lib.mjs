// Shared code of the design-system scripts (ADR-21): tokens, fonts, the
// bundle manifest, checksums.
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';

import { root } from './lib.mjs';

export const dsDir = join(root, 'design-system');
export const paths = {
  tokensJson: join(dsDir, 'tokens.json'),
  tokensCss: join(dsDir, 'tokens.css'),
  bundleJs: join(dsDir, 'components', 'bundle.js'),
  bundleCss: join(dsDir, 'components', 'bundle.css'),
  types: join(dsDir, 'components', 'index.d.ts'),
  fontsDir: join(dsDir, 'fonts'),
  fontsCss: join(dsDir, 'fonts', 'fonts.css'),
  changelog: join(dsDir, 'CHANGELOG.md'),
  checksums: join(dsDir, 'CHECKSUMS.sha256'),
};

export const sha256 = (data) => createHash('sha256').update(data).digest('hex');
export const readText = (file) => readFileSync(file, 'utf8');

// ---- tokens -------------------------------------------------------------------

export function readTokens(file = paths.tokensJson) {
  return JSON.parse(readText(file));
}

const cssValue = (value) => String(value).replace(/^\{([a-z0-9-]+)\}$/i, 'var(--$1)');

/** The stylesheet that defines every design token as a custom property. */
export function tokensCss(tokens) {
  const lines = [
    `/* ${tokens.name} design tokens, version ${tokens.version}.`,
    '   GENERATED from tokens.json by `pnpm ds:tokens`. Do not edit: change tokens.json.',
    '   This is the only stylesheet that holds colour values. */',
    ':root {',
  ];
  const group = (title, entries) => {
    lines.push(`  /* ${title} */`);
    for (const [name, value] of entries) lines.push(`  --${name}: ${cssValue(value)};`);
  };
  group('Colour', tokens.color.tokens.map((t) => [t.name, t.value]));
  group('Type', Object.entries(tokens.type.families).map(([name, value]) => [`font-${name}`, value]));
  group('Spacing', tokens.spacing.tokens.map((t) => [t.name, t.value]));
  group('Radius', tokens.radius.tokens.map((t) => [t.name, t.value]));
  group('Shadow', tokens.shadow.tokens.map((t) => [t.name, t.value]));
  group('Size', tokens.size.tokens.map((t) => [t.name, t.value]));
  lines.push('}', '');
  return lines.join('\n');
}

/** name → literal value, with `{alias}` resolved. */
export function colourMap(tokens) {
  const map = new Map(tokens.color.tokens.map((t) => [t.name, t.value]));
  for (const [name, value] of map) {
    const alias = /^\{([a-z0-9-]+)\}$/i.exec(value);
    if (alias) map.set(name, map.get(alias[1]));
  }
  return map;
}

// ---- fonts --------------------------------------------------------------------

/** The self-hosted fonts of the design system: family, package, subsets (Latin and Latin Extended for š č ć ž đ). */
export const FONTS = [
  { family: 'Manrope', id: 'manrope', pkg: '@fontsource-variable/manrope', subsets: ['latin-ext', 'latin'] },
  { family: 'Inter', id: 'inter', pkg: '@fontsource-variable/inter', subsets: ['latin-ext', 'latin'] },
];

function packageDir(pkg) {
  const require = createRequire(join(root, 'package.json'));
  return dirname(require.resolve(`${pkg}/package.json`));
}

/** The font files, their licences and the stylesheet, as they must be in design-system/fonts. */
export function fontRelease() {
  const files = new Map(); // name → Buffer | string
  const faces = [];
  const sources = [];
  for (const font of FONTS) {
    const dir = packageDir(font.pkg);
    const version = JSON.parse(readText(join(dir, 'package.json'))).version;
    sources.push(`${font.pkg}@${version}`);
    const css = readText(join(dir, 'wght.css'));
    files.set(`LICENSE-${font.family}.txt`, readFileSync(join(dir, 'LICENSE')));
    for (const subset of font.subsets) {
      const name = `${font.id}-${subset}-wght-normal.woff2`;
      files.set(name, readFileSync(join(dir, 'files', name)));
      const block = new RegExp(`/\\* ${font.id}-${subset}-wght-normal \\*/\\s*@font-face \\{([^}]*)\\}`).exec(css);
      if (!block) throw new Error(`No @font-face for ${name} in ${font.pkg}`);
      const field = (prop) => new RegExp(`${prop}:\\s*([^;]+);`).exec(block[1])?.[1].trim();
      faces.push(
        [
          `/* ${font.family}, ${subset} */`,
          '@font-face {',
          `  font-family: "${font.family}";`,
          '  font-style: normal;',
          '  font-display: swap;',
          `  font-weight: ${field('font-weight')};`,
          `  src: url("./${name}") format("woff2");`,
          `  unicode-range: ${field('unicode-range')};`,
          '}',
        ].join('\n'),
      );
    }
  }
  const header = [
    '/* UdEkoM Balkans design system: self-hosted fonts (no request leaves the site).',
    '   Manrope and Inter, variable weight, Latin and Latin Extended (š č ć ž đ).',
    `   GENERATED by \`pnpm ds:fonts\` from ${sources.join(' and ')}.`,
    '   Both families are under the SIL Open Font License 1.1; see the LICENSE files here. */',
  ].join('\n');
  files.set('fonts.css', `${header}\n\n${faces.join('\n\n')}\n`);
  return files;
}

// ---- bundle manifest ------------------------------------------------------------

/** Reads the `@ds-bundle` header of the bundle. */
export function readManifest(bundleText) {
  const match = /^\/\* @ds-bundle: (\{.*\}) \*\/\r?\n/.exec(bundleText);
  if (!match) throw new Error('The bundle has no @ds-bundle header on its first line');
  const manifest = JSON.parse(match[1]);
  return { ...manifest, componentNames: manifest.components.map((c) => c.name) };
}

/** Reads the `@ds-version` line of the bundle (version 2 and later). */
export function readBundleVersion(bundleText) {
  return /^\/\* @ds-version: (\d+\.\d+\.\d+) \*\/$/m.exec(bundleText)?.[1] ?? null;
}

// ---- release files and checksums ------------------------------------------------

/** Every file of the design-system release, sorted, as POSIX paths relative to design-system/. */
export function releaseFiles(dir = dsDir) {
  const out = [];
  const walk = (d) => {
    for (const name of readdirSync(d).sort()) {
      const path = join(d, name);
      if (statSync(path).isDirectory()) walk(path);
      else out.push(relative(dir, path).split('\\').join('/'));
    }
  };
  walk(dir);
  return out.filter((f) => f !== 'CHECKSUMS.sha256').sort();
}

/** Text files are hashed with LF line endings, so a checkout with CRLF gives the same checksum. */
const TEXT = /\.(md|json|js|css|ts|html|txt|sha256)$/;
export function fileChecksum(file, dir = dsDir) {
  const data = readFileSync(join(dir, file));
  return sha256(TEXT.test(file) ? data.toString('utf8').replace(/\r\n/g, '\n') : data);
}

/** The content of CHECKSUMS.sha256 for the current files. */
export function checksumsText(dir = dsDir) {
  return `${releaseFiles(dir).map((f) => `${fileChecksum(f, dir)}  ${f}`).join('\n')}\n`;
}
