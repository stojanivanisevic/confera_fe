// `pnpm ds:build`: generates the adapter around the design system (ADR-21).
//
// The design system is one plain script: it reads `window.React` and writes
// `window.Udekom`. That cannot run during server rendering. This step wraps the
// script, unchanged, in a client module in which `window` is a local object, so
// the same text renders on the server and hydrates in the browser. It also
// generates the type declarations (from the bundle's manifest and index.d.ts)
// and a manifest module.
//
// Output: packages/ui/src/generated/ (committed; `pnpm ds:check` fails when it is stale).
// With --check nothing is written and a difference is an error.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { fail, root } from './lib.mjs';
import { paths, readBundleVersion, readManifest, readText, readTokens, sha256 } from './ds-lib.mjs';

export const generatedDir = join(root, 'packages', 'ui', 'src', 'generated');

/** Members of window.Udekom that are not components. */
export const NON_COMPONENT_EXPORTS = ['toast', 'defaultLabels', 'version'];

/** The only ways the bundle may touch `window`: read React, write Udekom. */
export function windowReferences(bundle) {
  return [...bundle.matchAll(/\bwindow\b(?:\.([A-Za-z_$][\w$]*))?/g)].map((m) => m[1] ?? '(bare)');
}

export function checkTransforms(bundle) {
  const problems = [];
  const refs = windowReferences(bundle);
  const other = refs.filter((r) => r !== 'React' && r !== 'Udekom');
  if (!refs.includes('React')) problems.push('the bundle no longer reads window.React');
  if (!refs.includes('Udekom')) problems.push('the bundle no longer writes window.Udekom');
  if (other.length > 0) problems.push(`the bundle uses window for more than React and Udekom: ${[...new Set(other)].join(', ')}`);
  if (/\b(?:import|export)\s/.test(bundle.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(["'])(?:\\.|(?!\1).)*\1/g, '""'))) {
    problems.push('the bundle contains import or export statements; it must stay one plain script');
  }
  return problems;
}

/** The names of what the bundle really puts on window.Udekom, found by running it with a stand-in React. */
export function runtimeExports(bundle) {
  const element = () => ({});
  const React = {
    createElement: element,
    Fragment: 'fragment',
    Children: { only: (c) => c },
    cloneElement: element,
    createContext: () => ({ Provider: 'provider' }),
    useState: (v) => [v, () => {}],
    useEffect: () => {},
    useRef: () => ({ current: null }),
    useId: () => 'id',
    useContext: () => undefined,
    useMemo: (f) => f(),
    useCallback: (f) => f,
  };
  const sandbox = { React };
  // The bundle is first-party text from design-system/, executed at build time only to list its exports.
  new Function('window', bundle)(sandbox);
  if (!sandbox.Udekom) throw new Error('The bundle did not write window.Udekom');
  return Object.keys(sandbox.Udekom);
}

function propsInterfaces(types) {
  const found = new Map(); // name → generic parameter list or ''
  for (const m of types.matchAll(/^export interface (\w+)Props(<[^>{]*>)?/gm)) found.set(m[1], m[2] ?? '');
  return found;
}

export function buildAdapter() {
  const bundle = readText(paths.bundleJs).replace(/\r\n/g, '\n');
  const types = readText(paths.types).replace(/\r\n/g, '\n');
  const manifest = readManifest(bundle);
  const version = readBundleVersion(bundle) ?? String(readTokens().version);
  const checksum = sha256(bundle);
  const exported = runtimeExports(bundle);
  const extra = exported.filter((name) => !manifest.componentNames.includes(name));
  const banner = [
    `// GENERATED by \`pnpm ds:build\` from design-system/components/bundle.js. Do not edit.`,
    `// Design system ${manifest.namespace} ${version}; sha256 of the bundle: ${checksum}`,
  ].join('\n');

  const client = `'use client';
${banner}
//
// The text between the two marker lines is the design-system script, unchanged.
// It reads \`window.React\` and writes \`window.Udekom\`; here \`window\` is a
// local object, so the script also runs during server rendering. Everything
// that touches \`document\` inside it sits in effects and event handlers.
import * as React from 'react';

const Udekom = (function (window) {
// ---- design-system/components/bundle.js: begin ----
${bundle.trimEnd()}
// ---- design-system/components/bundle.js: end ----
  return window.${manifest.namespace};
})({ React });

${[...manifest.componentNames, ...extra].map((name) => `export const ${name} = Udekom.${name};`).join('\n')}
`;

  const interfaces = propsInterfaces(types);
  const declarations = manifest.componentNames.map((name) => {
    const generics = interfaces.get(name);
    if (generics === undefined) return `export declare const ${name}: React.FC<Record<string, unknown>>; // no ${name}Props in index.d.ts`;
    if (generics) {
      const use = `<${generics.slice(1, -1).split(',').map((p) => p.trim().split(/[\s=]/)[0]).join(', ')}>`;
      return `export declare function ${name}${generics}(props: ${name}Props${use}): React.ReactElement | null;`;
    }
    return `export declare const ${name}: React.FC<${name}Props>;`;
  });
  const dts = `${banner}
//
// Prop types: design-system/components/index.d.ts, unchanged, with React imported.
// Component declarations: one per entry of the bundle's manifest.
import type * as React from 'react';

${types.trimEnd()}

// ---------- Components (from the @ds-bundle manifest) ----------
${declarations.join('\n')}
`;

  const manifestTs = `${banner}

/** Version of the design system the adapter was generated from. */
export const DS_VERSION = ${JSON.stringify(version)};

/** sha256 of design-system/components/bundle.js. */
export const DS_BUNDLE_SHA256 = ${JSON.stringify(checksum)};

/** The components of the design system, in the order of its manifest. */
export const COMPONENT_NAMES = ${JSON.stringify(manifest.componentNames, null, 2).replace(/"/g, "'")} as const;

export type ComponentName = (typeof COMPONENT_NAMES)[number];
`;

  return new Map([
    ['udekom.client.js', client],
    ['udekom.client.d.ts', dts],
    ['manifest.ts', manifestTs],
  ]);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const problems = checkTransforms(readText(paths.bundleJs));
  if (problems.length > 0) fail(`The adapter cannot wrap this bundle:\n  - ${problems.join('\n  - ')}`);
  const files = buildAdapter();
  if (process.argv.includes('--check')) {
    const stale = [...files].filter(([name, text]) => {
      const file = join(generatedDir, name);
      return !existsSync(file) || readFileSync(file, 'utf8').replace(/\r\n/g, '\n') !== text;
    });
    if (stale.length > 0) fail(`The generated adapter is stale (${stale.map(([n]) => n).join(', ')}). Run \`pnpm ds:build\`.`);
    console.log('✓ the generated adapter equals what the bundle generates');
  } else {
    mkdirSync(generatedDir, { recursive: true });
    for (const [name, text] of files) writeFileSync(join(generatedDir, name), text);
    console.log(`packages/ui/src/generated written (${[...files.keys()].join(', ')})`);
  }
}
