/**
 * The texts of the admin screens (English; ADR-23: a typed catalogue, no i18n library).
 * They follow the design system's Voice: plain and warm, past-tense confirmations
 * ("Invitation sent"), errors that say how to fix the problem, named objects in confirmations.
 * `{name}` parts are filled with `fill`.
 */
export const fill = (text: string, values: Record<string, string | number>): string =>
  Object.entries(values).reduce((out, [key, value]) => out.split(`{${key}}`).join(String(value)), text);

